/**
 * Shape definitions for the Whiteboard.
 * All paths use a 100×100 viewBox coordinate system.
 */

export interface ShapeDef {
  id: string;
  /** i18n key for the shape's name; translate at render with t(). */
  labelKey: string;
  category: 'basic' | 'flowchart' | 'arrow' | 'uml' | 'er' | 'network' | 'bpmn' | 'wireframe' | 'callout' | 'infographic';
  path: string;
  deco?: string[];
  defaultWidth: number;
  defaultHeight: number;
  /** Percent (0–50) to inset connection handles from bounding box edges. 0 = at edge (rectangles). */
  handleInset?: number;
  /**
   * A picture of a thing (a person, a server) rather than a box to write in:
   * its label goes under it, where it can be read, instead of across it.
   */
  labelBelow?: boolean;
  /**
   * Where the words go, when that is not the middle: insets from the top,
   * right, bottom and left, in percent of the item. A class's name is in its
   * top compartment and a lifeline's in its head, not across the lines that
   * divide them.
   */
  labelBox?: [number, number, number, number];
}

